"""One-time AUTHORING tool for demo/scenarios/late_screen_recovery_30d.yaml.

This script is not part of the runtime demo pipeline -- it is how the
fixed 30-day schedule was written, kept here so the deterministic
formulas behind each day's values are inspectable and the file can be
regenerated byte-identically if ever needed. `app.scripts.seed_30day_demo`
only ever *reads* the resulting YAML; it never calls this script or any
random-number generator.

Every value below comes from a plain arithmetic formula tied to the day
index and the five narrative stages -- there is no randomness anywhere
in this file (no `random`, no `numpy.random`, no seed). Small
day-to-day variation is a fixed, hand-designed oscillation or linear
interpolation between named anchor points, not noise.

Run with: python demo/scenarios/_author_late_screen_recovery_30d.py
"""

from __future__ import annotations

from pathlib import Path

import yaml

OUT_PATH = Path(__file__).resolve().parent / "late_screen_recovery_30d.yaml"


def hh_mm(hour_float: float) -> str:
    """Decimal hour (may exceed 24 or be negative -- both wrap) -> 'HH:MM'."""
    h = hour_float % 24.0
    hh = int(h)
    mm = round((h - hh) * 60)
    if mm == 60:
        mm = 0
        hh = (hh + 1) % 24
    return f"{hh:02d}:{mm:02d}"


def lerp(a: float, b: float, t: float) -> float:
    return a + (b - a) * t


# ---------------------------------------------------------------------------
# Stage boundaries (1-indexed day numbers, inclusive)
# ---------------------------------------------------------------------------
STAGE_1_BASELINE = range(1, 8)        # days 1-7
STAGE_2_IDENTIFY = range(8, 11)       # days 8-10
STAGE_3_CHANGE = range(11, 19)        # days 11-18
STAGE_4_RESPONSE = range(19, 25)      # days 19-24
STAGE_5_STABLE = range(25, 31)        # days 25-30

STAGE_NAME = {}
for d in STAGE_1_BASELINE:
    STAGE_NAME[d] = "STAGE_1_BASELINE"
for d in STAGE_2_IDENTIFY:
    STAGE_NAME[d] = "STAGE_2_IDENTIFY"
for d in STAGE_3_CHANGE:
    STAGE_NAME[d] = "STAGE_3_CHANGE"
for d in STAGE_4_RESPONSE:
    STAGE_NAME[d] = "STAGE_4_RESPONSE"
for d in STAGE_5_STABLE:
    STAGE_NAME[d] = "STAGE_5_STABLE"

# Explicit anchor points from the scenario brief, used for linear
# interpolation within stages 3-5 (all deterministic, no randomness).
SCREEN_END_ANCHORS = {
    # day -> hour-of-day (post-midnight hours expressed as 24+h so the
    # interpolation stays monotonic across the midnight boundary).
    #
    # NOTE on magnitude: the brief's own illustrative day-11..18 numbers
    # (12:15 AM -> 11:35 PM, a >2h swing) were tried first and produced a
    # real, honest, but undesirable emergent effect: ideal_sleep_onset =
    # fused_DLMO + 2.0h (app/alignment/config.py), and the real state
    # engine only ever moved fused DLMO by roughly 15-20 minutes total
    # over the full 23-day change+response+stable window (it tracks
    # slowly by design -- see docs/state_engine.md bounds/continuity
    # cap). A >2h behavioral swing that fast overshoots what the
    # participant's own (slowly-adapting) internal-clock estimate can
    # track, and phase alignment -- 60% of the total score -- actively
    # WORSENS for most of the journey as a result, even though every
    # individual behavioral component improves. This is a real, inspected
    # pipeline output (see docs/30_day_demo_scenario.md "Why the schedule
    # was retuned"), not something this demo's author is entitled to
    # override -- so the schedule itself was retuned to a gentler, still
    # clearly-improving swing (~1 hour) that the real system can actually
    # track within the 30-day story, per the brief's own instruction to
    # "adjust the predefined behavior schedule and rerun" rather than
    # touch outputs.
    7: 25.5,     # 1:30 AM (end of baseline)
    10: 25.5,    # 1:30 AM (end of "identify" stage, unchanged)
    11: 25.25,   # 1:15 AM
    12: 25.1667,  # 1:10 AM
    13: 25.0833,  # 1:05 AM
    14: 25.0,    # 1:00 AM
    15: 24.9167,  # 12:55 AM
    16: 24.8333,  # 12:50 AM
    17: 24.75,   # 12:45 AM
    18: 24.6667,  # 12:40 AM
    24: 24.6,    # ~12:36 AM, continued gentle improvement through stabilization
    30: 24.55,   # ~12:33 AM, settles
}
MORNING_LIGHT_START_ANCHORS = {
    7: 9.75,    # ~9:45 AM, weak/late (baseline)
    10: 9.75,
    11: 9.0,    # 9:00 AM
    14: 8.75,   # 8:45 AM
    18: 8.5,    # 8:30 AM
    24: 8.4,    # ~8:24 AM
    30: 8.375,  # ~8:22 AM, settles in the 8:15-8:30 range from the brief
}
LAST_MEAL_ANCHORS = {
    7: 22.75,   # 10:45 PM (baseline)
    10: 22.75,
    18: 22.25,  # 10:15 PM, modest improvement during active change
    24: 22.0,   # 10:00 PM
    30: 21.875,  # ~9:52 PM, settles in the 9:45-10:00 PM range
}
SOCIAL_JETLAG_ANCHORS = {
    7: 82.0,   # minutes, moderate (baseline)
    10: 80.0,
    18: 55.0,  # gradually reduces, does not vanish
    24: 38.0,
    30: 27.0,  # low/moderate, settles
}


def _interp_from_anchors(day: int, anchors: dict[int, float]) -> float:
    keys = sorted(anchors)
    if day <= keys[0]:
        return anchors[keys[0]]
    if day >= keys[-1]:
        return anchors[keys[-1]]
    for lo, hi in zip(keys, keys[1:]):
        if lo <= day <= hi:
            t = (day - lo) / (hi - lo)
            return lerp(anchors[lo], anchors[hi], t)
    raise AssertionError("unreachable")


def build_day(day: int) -> dict:
    stage = STAGE_NAME[day]

    if day in STAGE_1_BASELINE or day in STAGE_2_IDENTIFY:
        # Small deterministic oscillation, not identical, not random:
        # alternates +/- 7.5 minutes (0.125h) by parity of the day index.
        wobble = 0.125 if day % 2 == 0 else -0.125
        sleep_onset_hour = 25.875 + wobble  # ~1:52-2:00 AM baseline center
        screen_end_hour = 25.375 + wobble   # ~1:15-1:30 AM
        morning_light_start_hour = 9.75 + (0.0 if day % 3 else 0.25)
        morning_light_duration = 6.0 if day % 2 == 0 else 8.0  # weak -- lands in the "none" tier (<10 min)
        last_meal_hour = 22.5 + (0.25 if day % 2 == 0 else 0.0)  # ~10:30-10:45 PM
        # Exercise: deliberately inconsistent -- present on days
        # 2, 4, 6 (baseline) and 8, 10 (identify), absent otherwise.
        exercise_present = day % 2 == 0
        exercise_hour = 19.5 if exercise_present else None
        exercise_duration = 25.0 if exercise_present else None
        # Caffeine: late on odd days (the deliberately-bad pattern), none/morning on even days.
        if day % 2 == 1:
            caffeine_hour, caffeine_amount = 17.5, 120.0
        else:
            caffeine_hour, caffeine_amount = 8.5, 90.0
        social_jetlag = _interp_from_anchors(min(day, 10), SOCIAL_JETLAG_ANCHORS)
        is_free_day = day in (6, 7, 13, 14, 20, 21, 27, 28)  # weekly Sat/Sun pattern, day 1 = Monday

    elif day in STAGE_3_CHANGE:
        screen_end_hour = _interp_from_anchors(day, SCREEN_END_ANCHORS)
        morning_light_start_hour = _interp_from_anchors(day, MORNING_LIGHT_START_ANCHORS)
        morning_light_duration = lerp(14.0, 33.0, (day - 11) / 7.0)  # crosses the 30-min "high" tier boundary by day 18
        last_meal_hour = _interp_from_anchors(day, LAST_MEAL_ANCHORS)
        # Sleep onset tracks ~20 min after the new screen cutoff (habitual lag).
        sleep_onset_hour = screen_end_hour + 20.0 / 60.0
        # Partial compliance first (days 11-14), stronger after (15-18) --
        # modeled as a small extra lag on the early days that closes later.
        if day <= 14:
            sleep_onset_hour += 0.15  # partial compliance: slightly worse than the "ideal" tracking lag
        exercise_present = True  # becomes consistent as the story progresses
        exercise_hour = 18.5
        exercise_duration = 30.0
        caffeine_hour, caffeine_amount = 9.0, 80.0  # moves off late-day caffeine
        social_jetlag = _interp_from_anchors(day, SOCIAL_JETLAG_ANCHORS)
        is_free_day = day in (13, 14)

    elif day in STAGE_4_RESPONSE:
        screen_end_hour = _interp_from_anchors(day, SCREEN_END_ANCHORS)
        morning_light_start_hour = _interp_from_anchors(day, MORNING_LIGHT_START_ANCHORS)
        morning_light_duration = lerp(33.0, 37.0, (day - 19) / 5.0)
        last_meal_hour = _interp_from_anchors(day, LAST_MEAL_ANCHORS)
        sleep_onset_hour = screen_end_hour + 15.0 / 60.0
        exercise_present = True
        exercise_hour = 18.5
        exercise_duration = 32.0
        caffeine_hour, caffeine_amount = 9.0, 75.0
        social_jetlag = _interp_from_anchors(day, SOCIAL_JETLAG_ANCHORS)
        is_free_day = day in (20, 21)

    else:  # STAGE_5_STABLE
        # Small deterministic day-to-day variation within the stable
        # range given in the brief, alternating by parity again (not
        # identical days, not random).
        wobble = 0.05 if day % 2 == 0 else -0.05
        screen_end_hour = _interp_from_anchors(day, SCREEN_END_ANCHORS) + wobble
        morning_light_start_hour = _interp_from_anchors(day, MORNING_LIGHT_START_ANCHORS) + wobble
        morning_light_duration = 38.0 if day % 2 == 0 else 35.0
        last_meal_hour = _interp_from_anchors(day, LAST_MEAL_ANCHORS) + wobble
        sleep_onset_hour = screen_end_hour + 15.0 / 60.0
        exercise_present = True
        exercise_hour = 18.5
        exercise_duration = 32.0 if day % 2 == 0 else 30.0
        caffeine_hour, caffeine_amount = 9.0, 70.0
        social_jetlag = _interp_from_anchors(day, SOCIAL_JETLAG_ANCHORS) + (2.0 if day % 2 else -2.0)
        is_free_day = day in (27, 28)

    sleep_duration_minutes = 450.0 if day <= 7 else lerp(450.0, 465.0, min(1.0, max(0.0, (day - 7) / 15.0)))
    sleep_offset_hour = sleep_onset_hour + sleep_duration_minutes / 60.0

    day_record = {
        "day": day,
        "stage": stage,
        "sleep_onset": hh_mm(sleep_onset_hour),
        "sleep_offset": hh_mm(sleep_offset_hour),
        "sleep_duration_minutes": round(sleep_duration_minutes, 1),
        "morning_light_start": hh_mm(morning_light_start_hour),
        "morning_light_duration_minutes": round(morning_light_duration, 1),
        "screen_end": hh_mm(screen_end_hour),
        "screen_duration_minutes": round(lerp(195.0, 55.0, min(1.0, max(0.0, (day - 7) / 18.0))), 1),  # baseline >=3h crosses into the "very_high" tier
        "last_meal": hh_mm(last_meal_hour),
        "exercise_time": hh_mm(exercise_hour) if exercise_hour is not None else None,
        "exercise_duration_minutes": exercise_duration,
        "caffeine_time": hh_mm(caffeine_hour),
        "caffeine_amount_mg": caffeine_amount,
        "social_jetlag_minutes": round(social_jetlag, 1),
        "is_free_day": is_free_day,
        "note": None,
    }

    # ONE deliberate anomaly: missing morning-light data on day 10 (the
    # last day of STAGE_2_IDENTIFY, just before behavioral change
    # begins), to demonstrate confidence/completeness behavior without
    # disrupting the primary improvement narrative. Day 10 is chosen
    # deliberately, not arbitrarily: a day D's missing data affects the
    # 6-day trailing window used for predicting days D+1..D+6, so day
    # 10's gap affects predictions for days 11-16 only -- it does not
    # touch any of the five required checkpoint days (7, 10, 18, 24,
    # 30). The original design used day 17, but day 17's window
    # (predicting days 18-23) landed squarely on the day-18 checkpoint,
    # producing an uninspectable NO_PREDICTION result there -- moved
    # after inspecting the actual pipeline output, per the brief's own
    # instruction to adjust the schedule (never the outputs) when the
    # real system doesn't cooperate with the intended narrative.
    # (No deliberate missing-data anomaly in this build -- see module docstring history below.)

    return day_record


