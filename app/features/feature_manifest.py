"""The authoritative CircadianIQ Version-1 feature manifest.

This is the single source of truth for every feature the builder
(``app.features.builder``) produces. The builder generates features
*from* this manifest -- iterating over ``MANIFEST`` and computing each
named feature -- rather than the manifest being documentation written
after the fact for an undocumented list scattered across files.

``docs/feature_engineering.md`` is generated by hand from this module
(kept in sync manually, since the module itself is already the
machine-readable form the brief asks for); ``len(MANIFEST) == 68`` is
asserted at import time so a silent count drift fails immediately
rather than being discovered downstream.

Feature groups, in the order they appear in ``MANIFEST``:

1. **Raw daily circular signals** (48): four non-sleep clock-time
   signals x six days x (sin, cos). See ``RAW_DAILY_SIGNALS`` for which
   four and why sleep timing is excluded.
2. **MSFsc, circular** (2): corrected free-day sleep midpoint for the
   window, sin/cos encoded.
3. **MEQ-derived** (2): ``MEQ_normalized`` and
   ``MEQ_MSFsc_divergence``.
4. **Flat window aggregates** (10): mean/std/ratio statistics over the
   six-day window.
5. **Recency-weighted aggregates** (6): the recency-weighted
   counterpart of six of the flat signals above.

48 + 2 + 1 + 1 + 10 + 6 = 68.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class FeatureSpec:
    """One row of the feature manifest -- one output column of the feature vector."""

    name: str
    source_signal: str
    day_relationship: str  # "day_1".."day_6", "window", or "participant"
    aggregation: str  # "raw", "circular_mean", "mean", "std", "ratio", "recency_weighted_mean", "derived"
    encoding: str  # "sin", "cos", "numeric"
    units: str
    tier: str  # "tier_1", "tier_2", "tier_3", "n/a"
    purpose: str
    circular: bool
    non_circular_reason: str = ""  # required (non-empty) when circular is False


# --- Group 1: raw daily circular signals -----------------------------------
#
# Four non-sleep clock-time signals, each represented on every one of the
# six window days as (sin, cos) -- never as a bare scalar hour.
#
# Sleep onset/offset/midpoint are deliberately excluded here (and
# everywhere else in this manifest): including them would let the model
# trivially reconstruct DLMO from sleep timing, which later phases will
# compare DLMO against for alignment scoring -- a self-referential loop
# this project explicitly avoids. See docs/feature_engineering.md
# "Anti-circularity" for the full rationale.
#
# The fourth signal (beyond the three explicitly named in the project
# brief -- evening screen end, last meal, morning light start) is
# EXERCISE TIMING, not sleep onset. Of the two remaining Phase 3 causal
# signals (exercise, caffeine), exercise timing is chosen here because
# exercise-timing phase-shift effects are more established in general
# chronobiology than caffeine-timing effects; caffeine amount is instead
# captured as a medium (non-circular) aggregate below. This choice is a
# feature-engineering design decision, not a literature-derived ranking.
RAW_DAILY_SIGNALS = (
    ("screen_end", "evening_screen_end_time", "tier_1", "Evening screen end time -- source-backed phase-delay signal (Phase 3 config)."),
    ("last_meal", "last_meal_time", "tier_2", "Last meal time -- source-backed phase-delay signal (Phase 3 config)."),
    ("morning_light_start", "morning_light_start_time", "tier_1", "Morning light start time -- source-backed phase-advance signal (Phase 3 config)."),
    ("exercise_time", "exercise_time", "tier_3", "Exercise timing -- illustrative phase-shift signal per the locked five-signal behavioral model."),
)


def _build_raw_daily_features() -> list:
    features = []
    for signal_key, source_signal, tier, purpose in RAW_DAILY_SIGNALS:
        for day_index in range(1, 7):
            for enc in ("sin", "cos"):
                features.append(
                    FeatureSpec(
                        name=f"{signal_key}_day_{day_index}_{enc}",
                        source_signal=source_signal,
                        day_relationship=f"day_{day_index}",
                        aggregation="raw",
                        encoding=enc,
                        units="unitless (circular)",
                        tier=tier,
                        purpose=purpose,
                        circular=True,
                    )
                )
    return features


