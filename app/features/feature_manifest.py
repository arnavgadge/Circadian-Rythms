MANIFEST: tuple = tuple(
    _build_raw_daily_features() + _MSFSC_FEATURES + _MEQ_FEATURES + _FLAT_AGGREGATE_FEATURES + _RECENCY_WEIGHTED_FEATURES
)

FEATURE_NAMES: tuple = tuple(spec.name for spec in MANIFEST)

TOTAL_FEATURE_COUNT = 68

# Bumped only if the manifest itself changes (feature added/removed/
# redefined) -- lets downstream consumers (Phase 11's daily pipeline
# provenance record) pin which manifest definition produced a given
# feature vector.
FEATURE_MANIFEST_VERSION = "1.0.0"

# Fail fast, at import time, if the manifest ever drifts from the locked
# count -- per the brief: "If implementation reveals an unavoidable count
# mismatch, STOP and document it rather than silently adding/removing
# features."
assert len(MANIFEST) == TOTAL_FEATURE_COUNT, (
    f"Feature manifest has {len(MANIFEST)} entries, expected {TOTAL_FEATURE_COUNT}. "
    "Do not silently change the feature count -- see docs/feature_engineering.md."
)
assert len(FEATURE_NAMES) == len(set(FEATURE_NAMES)), "Feature manifest contains duplicate names."

# Explicit, importable confirmation that no forbidden sleep-timing or
# physiology feature exists anywhere in the manifest (also re-checked by
# app.features.validation at runtime against a generated vector).
_FORBIDDEN_SUBSTRINGS = (
    "sleep_onset",
    "sleep_offset",
    "sleep_midpoint_sin",
    "sleep_midpoint_cos",
    "resting_hr",
    "hrv",
    "wrist_temp",
)
for _name in FEATURE_NAMES:
    for _forbidden in _FORBIDDEN_SUBSTRINGS:
        assert _forbidden not in _name, f"Forbidden feature '{_name}' matches banned pattern '{_forbidden}'"


def features_by_tier(tier: str) -> tuple:
    return tuple(spec for spec in MANIFEST if spec.tier == tier)


def feature_spec(name: str) -> FeatureSpec:
    for spec in MANIFEST:
        if spec.name == name:
            return spec
    raise KeyError(f"Unknown feature name: {name}")
