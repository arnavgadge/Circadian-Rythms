from __future__ import annotations

from datetime import date as date_type
from typing import Optional

from pydantic import BaseModel, Field, field_validator


def _validate_hhmm(value: Optional[str]) -> Optional[str]:
    if value is None:
        return value
    parts = value.split(":")
    if len(parts) != 2 or not all(p.isdigit() for p in parts):
        raise ValueError("must be in HH:MM format")
    hour, minute = int(parts[0]), int(parts[1])
    if not (0 <= hour < 24 and 0 <= minute < 60):
        raise ValueError("must be a valid 24h clock time")
    return value


class DailyEntryRequest(BaseModel):
    """One day's manually-logged behavioral baseline -- the only source
    of ``daily_observations`` rows for a participant not generated by
    the Phase 3 synthetic dataset. Pure data capture: no computation
    happens here or in the service that persists it."""

    observation_date: date_type
    sleep_onset_time: Optional[str] = Field(default=None, description="HH:MM (24h)")
    sleep_offset_time: Optional[str] = Field(default=None, description="HH:MM (24h)")
    morning_light_start_time: Optional[str] = Field(default=None, description="HH:MM (24h)")
    morning_light_duration_minutes: Optional[float] = Field(default=None, ge=0, le=600)
    evening_screen_end_time: Optional[str] = Field(default=None, description="HH:MM (24h)")
    evening_screen_duration_minutes: Optional[float] = Field(default=None, ge=0, le=1440)
    last_meal_time: Optional[str] = Field(default=None, description="HH:MM (24h)")
    exercise_time: Optional[str] = Field(default=None, description="HH:MM (24h)")
    last_caffeine_time: Optional[str] = Field(default=None, description="HH:MM (24h)")
    caffeine_amount_mg: Optional[float] = Field(default=None, ge=0, le=2000)
    is_free_day: Optional[bool] = None

    @field_validator(
        "sleep_onset_time", "sleep_offset_time", "morning_light_start_time",
        "evening_screen_end_time", "last_meal_time", "exercise_time", "last_caffeine_time",
    )
    @classmethod
    def _check_time(cls, value: Optional[str]) -> Optional[str]:
        return _validate_hhmm(value)


class DailyEntryResponse(BaseModel):
    participant_id: int
    observation_date: date_type
    saved: bool
